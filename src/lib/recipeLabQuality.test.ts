import { describe, expect, it } from "vitest";
import {
  parseRecipeLabJson,
  scoreRecipeLabCoverage,
  scoreRecipeLabDedupe,
  scoreRecipeLabQuality,
  type RecipeLabConstraint,
} from "./recipeLabQuality";
import type { RecipeLibraryInputFromSchema } from "./recipeLibrarySchema";

const source = {
  name: "Mammas Chef Generated Draft",
  url: null,
  author: "Mammas Chef",
  license: "ai-assisted internal draft",
  usageNotes: "Generated by internal recipe lab; requires review before publication or meal-plan use.",
};

function recipe(overrides: Partial<RecipeLibraryInputFromSchema> = {}): RecipeLibraryInputFromSchema {
  return {
    title: "Greek Yogurt Chickpea Breakfast Toast",
    cuisine: "Mediterranean",
    region: "Greek-inspired",
    mealTypes: ["breakfast"],
    dietTags: ["glucose-friendly", "toddler-adaptable"],
    flavorTags: ["lemon", "herbs"],
    equipment: ["toaster"],
    activeTimeMinutes: 10,
    totalTimeMinutes: 15,
    servings: 2,
    nutrition: { calories: 310, protein: 18, carbs: 35, fats: 11 },
    ingredients: [
      { name: "Greek yogurt", quantity: 0.75, unit: "cup", category: "dairy" },
      { name: "chickpeas", quantity: 1, unit: "cup", category: "pantry" },
      { name: "whole grain bread", quantity: 2, unit: "slices", category: "bakery" },
    ],
    steps: [
      { order: 1, text: "Toast the bread until crisp." },
      { order: 2, text: "Mash chickpeas with yogurt and spoon over toast." },
    ],
    storageNotes: "Store topping for 2 days.",
    reheatNotes: "Toast bread fresh.",
    prepAheadNotes: "Meal-prep friendly topping can be made ahead.",
    toddlerTip: "Serve as small strips for a toddler-adaptable breakfast.",
    glucoseTip: "Pair fiber-rich chickpeas with protein for glucose-friendly balance.",
    status: "draft",
    source,
    ...overrides,
  };
}

const constraint: RecipeLabConstraint = {
  day: 1,
  slot: 1,
  mealType: "breakfast",
  region: "Greek-inspired",
  protein: "eggs or Greek yogurt",
  time: "20 minutes or less",
  format: "portable weekday breakfast",
  familyConstraint: "toddler-adaptable without making a separate meal",
};

describe("recipeLabQuality", () => {
  it("parses fenced arrays and object-wrapped recipe output", () => {
    expect(parseRecipeLabJson("```json\n[{\"title\":\"A\"}]\n```")).toEqual([{ title: "A" }]);
    expect(parseRecipeLabJson("{\"recipes\":[{\"title\":\"B\"}]}")).toEqual([{ title: "B" }]);
  });

  it("scores coverage against recipe constraints", () => {
    const report = scoreRecipeLabCoverage([constraint], [recipe()]);

    expect(report.generated).toBe(1);
    expect(report.mealTypeCoverage.breakfast.generated).toBe(1);
    expect(report.prepTimeCoverage["20 minutes or less"].generated).toBe(1);
    expect(report.score).toBeGreaterThanOrEqual(0.8);
  });

  it("flags title and ingredient near-duplicates", () => {
    const report = scoreRecipeLabDedupe([
      recipe(),
      recipe({ title: "Greek Yogurt Chickpea Breakfast Toast", flavorTags: ["mint"] }),
    ]);

    expect(report.titleDuplicateCount).toBe(1);
    expect(report.score).toBeLessThan(1);
  });

  it("combines coverage and dedupe into a pass/fail report", () => {
    const report = scoreRecipeLabQuality([constraint], [recipe()]);

    expect(report.pass).toBe(true);
    expect(report.warnings).toEqual([]);
  });
});
